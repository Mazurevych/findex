"""Потоковий токенізатор.

`tokenize(text)` — генератор: токени віддаються по одному через `re.finditer`,
список усіх збігів (як у `re.findall`) ніколи не будується.

Правила (policy) — однакові для індексації і для запитів:

1. Unicode NFC. «é» може бути одним кодом U+00E9 або «e» + U+0301; після NFC
   обидва варіанти дають один і той самий токен.
2. `str.casefold()`, а не `lower()`: «Straße» і «STRASSE» -> «strasse».
3. Залишкові комбіновані знаки (U+0300–U+036F), які NFC не зміг «склеїти»
   з літерою, видаляються. Приклад: наголос у «за́мок» (а + U+0301 не має
   готового символу) — без цього слово розпалося б на «за» і «мок».
   Літери на кшталт «й», «ї», «é» не страждають: після NFC це цілі символи.
4. Апострофи. Варіанти ’ (U+2019), ʼ (U+02BC — український апостроф),
   ‘ (U+2018) і ` зводяться до звичайного '. Апостроф ВСЕРЕДИНІ слова
   лишається частиною токена: «п'ять», «don't», «rock'n'roll». Апострофи
   на краях слова (лапки) відкидаються: «'hello'» -> «hello».
5. Дефіси та інша пунктуація РОЗДІЛЯЮТЬ токени: «e-mail» -> «e», «mail»;
   «state-of-the-art» -> «state», «of», «the», «art». Так запит «mail» знайде
   «e-mail»; ціна — фразовий пошук (лаба 3) зможе склеїти частини назад.
6. Цифри — повноцінні токени: «2026» -> «2026»; «3.13» -> «3», «13»;
   «utf8» -> «utf8» (літери й цифри разом — одне слово).
7. Підкреслення входить у слово (як у `\\w`): для документації Python
   важливі ідентифікатори «__init__», «snake_case», «sys_path».
"""

from __future__ import annotations

import re
import unicodedata
from collections.abc import Iterator

# Апострофи, які вважаємо еквівалентними ASCII '
_APOSTROPHES = str.maketrans({"’": "'", "ʼ": "'", "‘": "'", "`": "'"})

# Комбіновані діакритичні знаки, що лишилися «осиротілими» після NFC
_COMBINING = re.compile(r"[̀-ͯ]")

# Слово = послідовність \w (літери будь-якої мови, цифри, _),
# можливо з'єднана одиночними апострофами: п'ять, don't, rock'n'roll.
WORD_RE = re.compile(r"\w+(?:'\w+)*")


def normalize(text: str) -> str:
    """NFC + casefold + прибирання осиротілих комбінованих знаків + апострофи."""
    text = unicodedata.normalize("NFC", text)
    text = text.casefold()
    text = _COMBINING.sub("", text)
    return text.translate(_APOSTROPHES)


def tokenize(text: str) -> Iterator[str]:
    """Віддає нормалізовані токени тексту по одному."""
    for match in WORD_RE.finditer(normalize(text)):
        yield match.group()
